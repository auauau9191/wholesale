// Turns the entity definitions in base44/entities/*.jsonc into:
//   src/lib/backend/schema.js  - fields, types, defaults and access rules the server uses at runtime
//   supabase/schema.sql        - the tables to create in Supabase (SQL editor → paste → Run)
// Run after changing an entity file:  node scripts/gen-backend-schema.mjs
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const dir = join(root, "base44/entities");

const parseJsonc = (text) =>
  JSON.parse(text.replace(/^\s*\/\/.*$/gm, "").replace(/,(\s*[}\]])/g, "$1"));

export const tableName = (entity) =>
  entity === "User" ? "users" : entity.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase();

const sqlType = (prop) => {
  switch (prop.type) {
    case "number": return "double precision";
    case "integer": return "integer";
    case "boolean": return "boolean";
    case "array":
    case "object": return "jsonb";
    default: return "text";
  }
};

const sqlLiteral = (value, prop) => {
  if (value === null || value === undefined) return null;
  if (prop.type === "array" || prop.type === "object") return `'${JSON.stringify(value).replace(/'/g, "''")}'::jsonb`;
  if (prop.type === "boolean") return value ? "true" : "false";
  if (prop.type === "number" || prop.type === "integer") return String(Number(value));
  return `'${String(value).replace(/'/g, "''")}'`;
};

const INDEXED = /(^|_)(code|no|id|email|status|user_email|product_id|hub_code|supplier_code|order_no|request_no|unit_id)$/;

const entities = {};
const sql = [
  "-- Wholesale System database. Generated by scripts/gen-backend-schema.mjs from base44/entities.",
  "-- Paste into Supabase → SQL Editor → Run. Safe to run again: it only adds what is missing.",
  "",
  "create extension if not exists pgcrypto;",
  "",
];

for (const file of readdirSync(dir).filter((f) => f.endsWith(".jsonc")).sort()) {
  const def = parseJsonc(readFileSync(join(dir, file), "utf8"));
  const name = def.name;
  const table = tableName(name);
  const fields = {};
  const fieldRules = {};
  for (const [key, prop] of Object.entries(def.properties ?? {})) {
    fields[key] = { type: prop.type ?? "string", ...(prop.format ? { format: prop.format } : {}), ...(prop.default !== undefined ? { default: prop.default } : {}) };
    if (prop.rls) fieldRules[key] = prop.rls;
  }
  if (name === "User") {
    fields.email = fields.email ?? { type: "string" };
    fields.full_name = fields.full_name ?? { type: "string" };
    fields.role = { type: "string", default: "user" };
    fields.auth_id = { type: "string" };
  }
  entities[name] = { table, fields, rules: def.rls ?? {}, fieldRules };

  const cols = [
    `  id text primary key default replace(gen_random_uuid()::text, '-', '')`,
    `  created_date timestamptz not null default now()`,
    `  updated_date timestamptz not null default now()`,
    `  created_by text`,
    `  created_by_id text`,
  ];
  for (const [key, prop] of Object.entries(fields)) {
    const def = sqlLiteral(prop.default, prop);
    const unique = name === "User" && (key === "email" || key === "auth_id") ? " unique" : "";
    cols.push(`  "${key}" ${sqlType(prop)}${def ? ` default ${def}` : ""}${unique}`);
  }
  cols.push(`  extra jsonb not null default '{}'::jsonb`);
  sql.push(`-- ${name}`);
  sql.push(`create table if not exists public.${table} (\n${cols.join(",\n")}\n);`);
  // Columns added to an entity later show up here on the next run.
  for (const [key, prop] of Object.entries(fields)) {
    const def = sqlLiteral(prop.default, prop);
    sql.push(`alter table public.${table} add column if not exists "${key}" ${sqlType(prop)}${def ? ` default ${def}` : ""};`);
  }
  for (const key of Object.keys(fields).filter((k) => INDEXED.test(k))) {
    sql.push(`create index if not exists ${table}_${key}_idx on public.${table} ("${key}");`);
  }
  // Only the app's server (which connects as the database owner) reads and writes these tables.
  // Row level security with no policies shuts out the public API keys completely.
  sql.push(`alter table public.${table} enable row level security;`);
  sql.push(`revoke all on table public.${table} from anon, authenticated;`);
  sql.push("");
}

const out = `// Generated by scripts/gen-backend-schema.mjs from base44/entities/*.jsonc. Do not edit by hand.\nexport const ENTITIES = ${JSON.stringify(entities, null, 2)};\n`;
mkdirSync(join(root, "src/lib/backend"), { recursive: true });
mkdirSync(join(root, "supabase"), { recursive: true });
writeFileSync(join(root, "src/lib/backend/schema.js"), out);
writeFileSync(join(root, "supabase/schema.sql"), sql.join("\n"));
console.log(`${Object.keys(entities).length} entities → src/lib/backend/schema.js, supabase/schema.sql`);
